/* بناء نص الإقلاع لكل بيئة. الصيغ هنا عقد ثابت تقرؤه مهارة /kickoff — لا تغيّر أسماء الحقول. */
(function () {
  'use strict';

  const TYPES = {
    web: 'تطبيق ويب متجاوب لجميع الشاشات',
    flutter: 'تطبيق جوال Flutter و Dart',
    rn: 'تطبيق جوال React Native',
    backend: 'مشروع باك إند وقاعدة بيانات فقط',
  };
  const SEP = '━━━━━━━━━━━━━━━━━━━━';
  const oneLine = (s) => String(s || '').replace(/\s*[\r\n]+\s*/g, ' ').trim();

  function designPrefs(d) {
    return {
      user: oneLine(d.audience) || 'لم يُحدد (استنتج من فكرة المشروع)',
      style: d.style || 'لم يُحدد (استنتج من طبيعة المشروع)',
      colorMode: d.colorMode || 'لم يُحدد (اختر الأنسب)',
      color: oneLine(d.color) || 'لم يُحدد (اختر ما يناسب الطابع)',
    };
  }

  /* Claude Code: مهارة /kickoff تحمل كل التعليمات، فيكفي سطر الأمر ثم حقل واحد في كل سطر. */
  function claude(d) {
    const lines = ['/kickoff',
      `اسم المشروع: ${oneLine(d.name)}`, `طبيعة المشروع: ${TYPES[d.type]}`, `الفكرة المبدئية: ${oneLine(d.idea)}`,
      `وضع التشغيل: ${d.mode}`, `اسم النداء: ${oneLine(d.callSign)}`, `مستوى الخبرة: ${d.level}`];
    if (d.type === 'backend') {
      lines.push('ملاحظة: المشروع باك إند فقط — لا واجهات مستخدم؛ مُراجع UI/UX معطّل.');
    } else {
      const p = designPrefs(d);
      lines.push(SEP, `المستخدم النهائي: ${p.user}`, `طابع التصميم: ${p.style}`, `الوضع البصري: ${p.colorMode}`, `اللون الرئيسي المفضل: ${p.color}`);
    }
    return lines.join('\n');
  }

  /* Cursor: البيانات نفسها، لكن المهارة تُقرأ من ملفها لأن قائمة أوامر Cursor قد لا تعرضها. */
  function cursor(d) {
    return claude(d).replace('/kickoff', 'نفّذ أمر kickoff: اقرأ الملف .claude/skills/kickoff/SKILL.md ونفّذه كاملاً بالبيانات التالية:');
  }

  /* OpenCode: الأمر /kickoff موجود في قائمته، لكن النص متعدد الأسطر بعد الأمر قد لا يصل كاملاً، فيُطلب تحميل المهارة صراحةً. */
  function opencode(d) {
    return claude(d).replace('/kickoff', 'نفّذ أمر kickoff: حمّل المهارة kickoff بأداة skill ونفّذها كاملةً بالبيانات التالية:');
  }

  /* Antigravity: برومبت إقلاع كامل لأن البيئة لا تملك مهارة /kickoff. */
  function antigravity(d) {
    const modeText = d.mode === 'prototype' ? 'prototype للتجريب السريع وبناء النموذج الأولي' : 'production للإنتاج الكامل بصرامة جميع القواعد';
    const learning = d.level === 'مطوّر' ? '' : ' — فعّل وضع التعلّم: اشرح كل قرار أو تعديل مهم بسطرين أو ثلاثة بلغة بسيطة، وعرّف كل مصطلح تقني عند أول ظهوره.';
    let design;
    if (d.type === 'backend') {
      design = '\n10. المشروع باك إند فقط — لا واجهات مستخدم مطلوبة. عطّل مُراجع UI/UX تلقائياً وحوّل وزنه التقييمي لمُراجع الأمن والأداء.';
    } else {
      const p = designPrefs(d);
      design = `\n\n${SEP}\n🎨 تفضيلات التصميم\n${SEP}\n10. المستخدم النهائي: ${p.user}\n11. طابع التصميم: ${p.style}\n12. الوضع البصري: ${p.colorMode}\n13. اللون الرئيسي المفضل: ${p.color}\n\n⚠️ تعليمات التصميم للوكيل:\n- لا تسأل عن تفضيلات التصميم — البيانات أعلاه كافية للبدء.\n- سجّل هذه التفضيلات في قسم "تفضيلات التصميم" بملف project_map.md.\n- أنشئ ملف المتغيرات (tokens) في بداية مرحلة الواجهات بعد اعتماد الـ Tech Stack (البند 17 — rules_ui.md)، بقيم فعلية لا مؤقتة.\n- ابنِ نموذجاً تجريبياً للشاشة الرئيسية واعرضه قبل البناء الكامل، واسأل سؤالاً واحداً: "هل هذا الاتجاه البصري يعكس تصورك؟"`;
    }
    return `السلام عليكم. أنا مستخدم Vibe Builder، وهذا المجلد يحتوي على ملفات الإدارة الأساسية في الجذر. بما أنك تعمل داخل بيئة Antigravity 2.0 وتملك صلاحيات الملفات والطرفية، نفّذ المهام التالية فوراً وبشكل تلقائي:

1. اقرأ جميع الملفات الحاكمة التسعة والتزم ببروتوكول بداية الجلسة (Session Start Protocol) حسب الترتيب الإجباري: master_rules.md، rules_security.md، rules_code_quality.md، rules_workflow.md، rules_ui.md، project_map.md، وآخر 5 مدخلات في changelog.md، والأخطاء النشطة في bugs_log.md، وآخر 5 قرارات في decisions_log.md بالإضافة إلى .agents/AGENTS.md واعتبرها الدستور الحاكم الصارم لك.
2. تأكد من استيعاب كافة القواعد والقوانين الحاكمة (اللغة العربية الفصحى، حماية قواعد الأمان في Firebase، منع الكسل، سقف حجم الملفات حسب نوعها (البند 14)، تتبّع الهجرات SQL، وحظر فوضى الحزم).
3. استخدم الطرفية والـ Sandbox المدمج لديك لتشغيل الفحص البيئي (Environment Audit) لمعرفة نظام تشغيلي وإصدارات (Node/Python/Git) والمنافذ المتاحة، وسجّل النتائج فوراً في قسم البيئة المحلية بملف project_map.md.

${SEP}
📋 بيانات المشروع
${SEP}
4. اسم مشروعي الجديد هو: ${oneLine(d.name)}
5. طبيعة المشروع وهويته التقنية هي: ${TYPES[d.type]}
6. الفكرة المبدئية في عقلي هي: ${d.idea.trim()}
7. وضع التشغيل المطلوب هو: ${modeText}
8. اسم النداء الخاص بي هو: ${oneLine(d.callSign)}
9. مستوى خبرتي البرمجية: ${d.level}${learning}${design}

${SEP}
بعد إنهاء الفحص البيئي وتحديث المستندات، ابدأ العصف الذهني واطرح أسئلتك حبة حبة لتفكيك الـ MVP دون أي تأخير أو كود ناقص، واقترح الـ Tech Stack من المخطط المطابق لطبيعة المشروع في مجلد blueprints/.`;
  }

  const NEXT_STEPS = {
    claude: [
      'افتح تطبيق Claude لسطح المكتب، ثم تبويب <strong>Code</strong>، واختر <strong>مجلد المشروع نفسه</strong> (الجذر الذي يحتوي هذا الملف).',
      'إذا ظهرت رسالة «الثقة بالمجلد» فوافق عليها — ملفات <bdi>.claude/hooks</bdi> سكربتات صغيرة تحمي مشروعك وتفرض القواعد.',
      'الصق النص في صندوق المحادثة واضغط إرسال.',
      'أجب عن أسئلة العصف الذهني — الوكيل يتولى الباقي خطوة بخطوة.',
    ],
    antigravity: [
      'افتح مجلد المشروع في Google Antigravity 2.0.',
      'افتح محادثة جديدة مع الوكيل.',
      'الصق النص واضغط إرسال.',
      'أجب عن أسئلة العصف الذهني حبة حبة حتى يكتمل تصور الـ MVP.',
    ],
    cursor: [
      'افتح <strong>مجلد المشروع نفسه</strong> في Cursor (الجذر الذي يحتوي هذا الملف)، ووافق على «الثقة بالمجلد».',
      'افتح محادثة جديدة مع الوكيل في وضع <strong>Agent</strong>.',
      'الصق النص واضغط إرسال.',
      'للأوامر لاحقاً اكتب اسمها للوكيل، مثل: «نفّذ next» لمعرفة الخطوة التالية.',
    ],
    opencode: [
      'افتح تطبيق OpenCode، ثم افتح <strong>مجلد المشروع نفسه</strong> (الجذر الذي يحتوي هذا الملف).',
      'ابدأ جلسة جديدة، والصق النص واضغط إرسال.',
      'إذا ظهرت نافذة تطلب موافقتك فاقرأ سببها: وافق إن كان ما يطلبه الوكيل هو ما طلبتَه أنت.',
      'للأوامر لاحقاً اكتب <bdi>/</bdi> واختر من القائمة، مثل <bdi>/next</bdi> لمعرفة الخطوة التالية.',
    ],
  };

  /* نص الإرشاد فوق الناتج لكل بيئة. */
  const RESULT_LEADS = {
    claude: 'انسخه والصقه في Claude Code داخل جذر مجلد المشروع. إذا لم يبدأ الإقلاع تلقائياً فاكتب ⁦/kickoff⁩ ثم الصق النص.',
    antigravity: 'انسخه وأرسله للوكيل في محادثة جديدة داخل Antigravity.',
    cursor: 'انسخه وأرسله للوكيل في محادثة جديدة داخل Cursor، من جذر مجلد المشروع.',
    opencode: 'انسخه وأرسله في جلسة جديدة داخل OpenCode، بعد فتح جذر مجلد المشروع.',
  };

  window.AGL = { TYPES, claude, antigravity, cursor, opencode, NEXT_STEPS, RESULT_LEADS };
})();
